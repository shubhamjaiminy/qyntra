/** Values no form should accept for a field with this label. */
export function invalidValueFor(label: string): string | undefined {
  if (/%|percent|discount|rate/i.test(label)) return '150';
  if (/amount|price|fee|cost|quantity|qty|days|count|number of/i.test(label)) return '-5';
  return undefined;
}

/**
 * Probes for a form reached by `setup`. Text fields are filled so that
 * only the value under test is wrong; the oracle is that the form shows
 * an error and makes no attempt to save.
 */
export async function formProbes(page: Page, setup: string[]): Promise<Probe[]> {
  // A real submit: a Save/Submit/Create/Add button that is not a link
  // elsewhere, not in a toolbar or header, with fields to fill in the
  // same form or container. "Add a New Rule" on a list page opens a
  // form; "Save Filters" in a table toolbar saves a view. Neither
  // submits one.
  // Passed as a string: code given to page.evaluate as a function is
  // compiled by tsx, which inserts a __name() helper into named inner
  // functions — undefined in the browser, so the probe silently vanished.
  const located = (await page.evaluate(String.raw`(() => {
    const FIELD = 'input:not([type=hidden]):not([type=search]):not([type=checkbox]):not([type=radio]), textarea';
    const visible = (element) => !!(element.offsetWidth || element.offsetHeight);
    const name = (element) => (element.getAttribute('aria-label') || element.textContent || '').trim().replace(/\s+/g, ' ');

    const buttons = Array.from(document.querySelectorAll('button, [role=button], input[type=submit]')).filter(
      (button) =>
        visible(button) &&
        !button.closest('a, nav, aside, header, [role=toolbar], [role=banner], [role=navigation]') &&
        /^(save|submit|create|add)\b/i.test(name(button) || button.value || '')
    );

    const found = [];

    for (const button of buttons) {
      let container = button.closest('form');

      for (let up = button.parentElement, depth = 0; !container && up && up !== document.body && depth < 8; up = up.parentElement, depth += 1) {
        if (Array.from(up.querySelectorAll(FIELD)).some(visible)) container = up;
      }

      const fields = container ? Array.from(container.querySelectorAll(FIELD)).filter(visible).length : 0;

      if (fields > 0) {
        found.push({
          name: name(button) || button.value,
          disabled: button.disabled || button.getAttribute('aria-disabled') === 'true',
          fields,
        });
      }
    }

    return found;
  })()`)) as { name: string; disabled: boolean; fields: number }[];

  if (located.length !== 1) {
    return [];
  }

  const submitName = located[0].name;
  const submitCode = `page.getByRole('button', { name: ${quote(submitName)}, exact: true })`;

  if ((await page.getByRole('button', { name: submitName, exact: true }).count()) !== 1) {
    return [];
  }

  // A submit that is disabled until the form is valid: the rule is that
  // it stays disabled while the form is empty.
  if (located[0].disabled) {
    return [
      {
        kind: 'validation',
        description: `Left the form empty: "${submitName}" should stay disabled`,
        setup,
        test: {
          title: `"${submitName}" is disabled while the form is empty`,
          intent: 'Protects required-field validation on a form that disables submit until it is valid.',
          body: body([...setup, `await expect(${submitCode}).toBeDisabled();`]),
        },
      },
    ];
  }

  // Error-looking text already on the form would satisfy the oracle
  // without the form rejecting anything. Such a form cannot be judged.
  const preexisting = await page
    .locator('[role=alert]:not(:empty), [aria-invalid=true]')
    .or(page.getByText(new RegExp(ERROR_TEXT, 'i')))
    .count();

  if (preexisting > 0) {
    return [];
  }

  // Every fillable field, so a probe can make all but one valid.
  const fields: { code: string; label: string; type: string }[] = [];

  for (const field of await page.$$('input:not([type=hidden]):not([type=checkbox]):not([type=radio]):not([type=search]), textarea')) {
    if (!(await field.isVisible())) continue;

    const code = await controlCode(page, field);
    if (!code) continue;

    fields.push({
      code,
      label: /getByLabel\('((?:\\.|[^'])*)'/.exec(code)?.[1] ?? '',
      type: await field.evaluate((node) => (node as HTMLInputElement).type || 'text'),
    });
  }

  const validValue = (type: string) => (type === 'email' ? 'qyntra@example.com' : type === 'number' ? '1' : type === 'url' ? 'https://example.com' : 'Qyntra check');

  const fillAllBut = (except: string) =>
    fields
      .filter((field) => field.code !== except && ['text', 'textarea', 'email', 'number', 'url', 'tel'].includes(field.type))
      .map((field) => `await ${field.code}.fill(${quote(validValue(field.type))});`);

  /**
   * Rejected: a visible error, or the browser's own validation blocking
   * the submit. Native validity only counts when the form lets the
   * browser block it — with novalidate, an "invalid" field still saves.
   */
  const rejected = (what: string, fieldCode?: string) => [
    `await ${submitCode}.click();`,
    'await expect.poll(async () => {',
    "  const shown = await page.locator('[role=alert]:not(:empty), [aria-invalid=true]')",
    `    .or(page.getByText(/${ERROR_TEXT}/i)).first().isVisible().catch(() => false);`,
    fieldCode
      ? `  const blocked = await ${fieldCode}.evaluate((field) => !field.validity.valid && !(field.form && field.form.noValidate)).catch(() => false);`
      : "  const blocked = await page.locator('input, textarea, select').evaluateAll((all) => all.some((field) => field.willValidate && !field.validity.valid && !(field.form && field.form.noValidate))).catch(() => false);",
    '  return shown || blocked;',
    `}, { message: ${JSON.stringify(what)}, timeout: 5_000 }).toBe(true);`,
  ];

  const probes: Probe[] = [
    {
      kind: 'validation',
      description: 'Submitted the form empty: it should show an error',
      setup,
      test: {
        title: `Submitting the empty form shows an error`,
        intent: 'Protects required-field validation.',
        body: body([...setup, ...rejected('an empty form should be rejected with a visible error')]),
      },
    },
  ];

  for (const field of fields) {
    const value = field.type === 'email' || /e-?mail/i.test(field.label) ? 'not-an-email' : field.type === 'number' ? invalidValueFor(field.label) : undefined;

    if (!value) continue;

    probes.push({
      kind: 'validation',
      description: `Entered ${value} in "${field.label}": it should be rejected`,
      setup,
      test: {
        title: `"${field.label}" rejects ${value}`,
        intent: `Protects validation: ${value} is never a valid "${field.label}".`,
        body: body([
          ...setup,
          ...fillAllBut(field.code),
          `await ${field.code}.fill(${quote(value)});`,
          ...rejected(`${value} in "${field.label}" should be rejected with a visible error`, field.code),
        ]),
      },
    });
  }

  return probes;
}

/**
 * Judge a failed probe test. Its oracle is generic, not a guess, so an
 * assertion failure is evidence about the application; a failure to act
 * (an element not found to click or fill) means the probe itself broke.
 */
export function probeFailureIsDefect(error: string): boolean {
  if (error.includes(MISAIMED)) return false;

  const assertion = /expect\(|toPass|toBeVisible|toBeLessThan|toContain/.test(error);
  const actionFailed = /locator\.(fill|click|selectOption|check)\b|page\.goto/.test(error);

  return assertion && !actionFailed;
}
