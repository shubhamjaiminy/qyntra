/**
 * Behaviour probes: experiments the explorer runs itself, with oracles
 * that hold for any application.
 *
 *   search      typing a word from one row leaves fewer rows, all containing it
 *   filter      choosing an option leaves only rows with a cell equal to it
 *   sort        a sortable column, or a "sort by" dropdown such as "Price (high
 *               to low)", puts the rows in that order, and the reverse
 *   validation  an empty form, and an out-of-range number, are rejected with
 *               a visible error and no attempt to save
 *
 * A model asked to "test the search" writes a test that checks the search
 * box exists. A probe checks that search searches. Each probe becomes a
 * Playwright test generated by code, not by a model, so it cannot be
 * weakened into passing; when the application breaks the rule, the test
 * fails, and that failure is the catch.
 */

import type { Page } from '@playwright/test';

import type { WrittenTest } from './feature-ai';

// --------------------------------------------------
// SHAPES
// --------------------------------------------------

export interface Probe {
  kind: 'search' | 'filter' | 'sort' | 'pagination' | 'validation';
  /** What the probe does, for the report. */
  description: string;
  /** Code that reaches the view the probe runs on, e.g. a click. Empty for the feature page. */
  setup: string[];
  /** The generated test. */
  test: WrittenTest;
}

/** Rows of the feature's main table or grid, excluding header rows. */
const ROW_SELECTORS = ['tbody tr:visible', '[role=row]:has([role=gridcell]):visible', '[role=row]:has([role=cell]):visible'];

const SEARCH_LABEL = /search|filter|find/i;
const FILTER_LABEL = /status|state|type|category|filter|show/i;
const ERROR_TEXT = 'must|invalid|required|between|at least|at most|maximum|minimum|cannot|can\'t|please|not allowed|greater|less than';

const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

// --------------------------------------------------
// HELPERS
// --------------------------------------------------

async function rowSelector(page: Page): Promise<string | undefined> {
  for (const selector of ROW_SELECTORS) {
    if ((await page.locator(selector).count().catch(() => 0)) >= 2) {
      return selector;
    }
  }

  return cardSelector(page);
}

/**
 * Items shown as cards rather than table rows, as product grids are: the
 * largest group of three or more visible siblings sharing a tag and
 * class, each with text of its own, outside navigation. Returned as a
 * selector that matches exactly that group.
 *
 * Never inside a table: a table with one data row has no list to probe,
 * and its header cells are not items. Generated class names (MUI's
 * jss274, CSS-module hashes) are left out of the selector, since they
 * change between builds.
 */
export async function cardSelector(page: Page): Promise<string | undefined> {
  const found = await page.evaluate(() => {
    let best: { selector: string; size: number } | undefined;

    for (const parent of Array.from(document.querySelectorAll('body *'))) {
      if (parent.closest('nav, header, footer, [role=navigation], [role=menu], select, ul[role=listbox], table, [role=table], [role=grid], [role=row]')) continue;

      const groups = new Map<string, Element[]>();

      for (const child of Array.from(parent.children)) {
        const element = child as HTMLElement;
        // A digit marks a generated name (jss274, css-1x2y3z, title__a1B2c).
        const classes = Array.from(element.classList).filter((name) => /^[A-Za-z_-][\w-]*$/.test(name) && !/\d/.test(name));
        if (classes.length === 0 || !element.offsetParent || !(element.innerText || '').trim()) continue;

        const key = `${element.tagName.toLowerCase()}.${classes.join('.')}`;
        groups.set(key, [...(groups.get(key) ?? []), element]);
      }

      for (const [selector, members] of groups) {
        const texts = new Set(members.map((member) => (member as HTMLElement).innerText.trim()));
        if (members.length < 3 || texts.size < members.length) continue;
        if (document.querySelectorAll(selector).length !== members.length) continue;
        if (!best || members.length > best.size) best = { selector, size: members.length };
      }
    }

    return best?.selector;
  });

  return found ? `${found}:visible` : undefined;
}

/**
 * The text of a control's label, without the control's own text. A
 * <select> inside its <label> otherwise reads "Status All Active
 * Inactive", which matches no locator.
 */
function labelText(node: Element): string {
  const field = node as HTMLInputElement;
  const aria = field.getAttribute('aria-label');

  if (aria) {
    return aria.trim().replace(/\s+/g, ' ');
  }

  const label = field.labels?.[0];

  if (!label) {
    return '';
  }

  const copy = label.cloneNode(true) as HTMLElement;
  copy.querySelectorAll('input, select, textarea, option').forEach((child) => child.remove());

  return (copy.textContent ?? '').trim().replace(/\s+/g, ' ');
}

/** A Playwright expression for a form control, by its accessible label. */
async function controlCode(page: Page, element: import('@playwright/test').ElementHandle): Promise<string | undefined> {
  const label = await element.evaluate(labelText);

  if (!label) {
    return undefined;
  }

  // Only a label that singles out this control is a usable locator.
  if ((await page.getByLabel(label, { exact: true }).count()) === 1) {
    return `page.getByLabel(${quote(label)}, { exact: true })`;
  }

  // A <select> wrapped in its <label> is named "Status All" (label plus
  // the selected option), so the exact label matches nothing. A
  // substring match is fine when it still singles out one control.
  if ((await page.getByLabel(label).count()) === 1) {
    return `page.getByLabel(${quote(label)})`;
  }

  return undefined;
}

/**
 * A word from the rows that the fewest rows contain (but at least one):
 * the query that should narrow the list the most.
 */
export function distinctiveWord(rows: string[]): string | undefined {
  let best: { word: string; containing: number } | undefined;

  for (const row of rows) {
    for (const word of row.split(/[^A-Za-z0-9]+/)) {
      if (word.length < 4 || /^\d+$/.test(word)) continue;

      const lower = word.toLowerCase();
      const containing = rows.filter((other) => other.toLowerCase().includes(lower)).length;

      if (containing < rows.length && (!best || containing < best.containing)) {
        best = { word, containing };
      }
    }
  }

  return best?.word;
}

function body(lines: string[]): string {
  return lines.join('\n');
}

/** Marker in the error a probe throws when its self-check withdraws it. */
export const MISAIMED = 'Qyntra withdrew this finding';

/**
 * A list probe with a self-check. Before acting, it records the items it
 * tracks and the list or table around them. If the probe then fails while
 * its items are unchanged but the list around them did change ("no
 * matching records", a new count), it was watching the wrong elements,
 * such as a table's header cells: the failure is Qyntra's, not the
 * application's, and is reported as such rather than as a defect.
 */
export function witnessed(rows: string, lines: string[]): string {
  return body([
    `const qyntraItems = page.locator(${quote(rows)});`,
    "await qyntraItems.first().evaluate((item) => { const list = item.closest('table, [role=grid], [role=table]') || item.parentElement; if (list) list.setAttribute('data-qyntra-list', ''); }).catch(() => undefined);",
    "const qyntraList = () => page.locator('[data-qyntra-list]').first().innerText().catch(() => '');",
    "const qyntraItemsBefore = (await qyntraItems.allInnerTexts()).join('\\n');",
    'const qyntraListBefore = await qyntraList();',
    'try {',
    ...lines.map((line) => `  ${line}`),
    '} catch (error) {',
    "  const itemsNow = (await qyntraItems.allInnerTexts()).join('\\n');",
    '  const listNow = await qyntraList();',
    '  if (itemsNow === qyntraItemsBefore && listNow !== qyntraListBefore) {',
    `    throw new Error(${quote(`${MISAIMED}: the list on the page changed, but the elements this check watches did not, so it was watching the wrong thing. Not a finding about the application.`)});`,
    '  }',
    '  throw error;',
    '}',
  ]);
}

