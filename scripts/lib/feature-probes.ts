// SEARCH AND FILTER (on the feature page)
// --------------------------------------------------

export async function listProbes(page: Page): Promise<Probe[]> {
  const probes: Probe[] = [];
  const rows = await rowSelector(page);

  if (!rows) {
    return probes;
  }

  const rowTexts = await page.locator(rows).allInnerTexts();

  // Search: an input labelled like one. Data-table toolkits (MUI
  // DataTables among them) hide it behind a "Search" button until opened.
  const searchSetup: string[] = [];
  const findInputs = () => page.$$('input[type=search], input[type=text], input:not([type]), [role=searchbox]');
  let inputs = await findInputs();

  const hasVisibleSearch = async () => {
    for (const input of inputs) {
      if ((await input.isVisible()) && SEARCH_LABEL.test(`${await input.evaluate(labelText)} ${await input.getAttribute('placeholder') ?? ''} ${await input.getAttribute('type') ?? ''}`)) {
        return true;
      }
    }
    return false;
  };

  const opener = page.getByRole('button', { name: 'Search', exact: true });

  if (!(await hasVisibleSearch()) && (await opener.count()) === 1) {
    await opener.click();
    await page.waitForTimeout(800);
    inputs = await findInputs();
    searchSetup.push("await page.getByRole('button', { name: 'Search', exact: true }).click();");
  }

  for (const input of inputs) {
    if (!(await input.isVisible())) continue;

    const label = `${await input.evaluate(labelText)} ${await input.getAttribute('placeholder') ?? ''} ${await input.getAttribute('type') ?? ''}`;

    if (!SEARCH_LABEL.test(label)) continue;

    // An opened search box is often unlabelled: fall back to its
    // placeholder, or to the only visible search-type input.
    const placeholder = await input.getAttribute('placeholder');
    const code =
      (await controlCode(page, input)) ??
      (placeholder && (await page.getByPlaceholder(placeholder, { exact: true }).count()) === 1
        ? `page.getByPlaceholder(${quote(placeholder)}, { exact: true })`
        : (await page.locator('input[type=search]:visible').count()) === 1
          ? "page.locator('input[type=search]:visible')"
          : undefined);
    const word = distinctiveWord(rowTexts);

    if (!code || !word) continue;

    probes.push({
      kind: 'search',
      description: `Searched for "${word}": fewer rows should remain, all containing it`,
      setup: searchSetup,
      test: {
        title: `Search for "${word}" shows only matching rows`,
        intent: 'Protects search: it must narrow the list to rows that contain the query.',
        body: witnessed(rows, [
          `const rows = page.locator(${quote(rows)});`,
          'const before = await rows.count();',
          ...searchSetup,
          `await ${code}.fill(${quote(word)});`,
          'await expect(async () => {',
          '  const shown = await rows.allInnerTexts();',
          '  expect(shown.length, "rows left after searching").toBeGreaterThan(0);',
          '  expect(shown.length, "search should narrow the list").toBeLessThan(before);',
          `  for (const text of shown) expect(text.toLowerCase(), "every row should contain the query").toContain(${quote(word.toLowerCase())});`,
          '}).toPass({ timeout: 10_000 });',
        ]),
      },
    });
    break;
  }

  // Leave the page as found for the filter probe.
  if (searchSetup.length > 0) {
    await page.keyboard.press('Escape').catch(() => undefined);
  }

  // Filter: a native select whose label says what it filters by.
  for (const select of await page.$$('select')) {
    if (!(await select.isVisible())) continue;

    const label = await select.evaluate(labelText);
    if (!FILTER_LABEL.test(label)) continue;

    const code = await controlCode(page, select);
    if (!code) continue;

    const options = await select.evaluate((node) =>
      Array.from((node as HTMLSelectElement).options).map((option) => option.label.trim())
    );

    const option = splittingOption(options, await rowCells(page, rows));

    if (!option) continue;

    probes.push({
      kind: 'filter',
      description: `Filtered by ${label.trim()} = "${option}": only rows showing "${option}" should remain`,
      setup: [],
      test: {
        title: `Filter "${option}" shows only "${option}" rows`,
        intent: 'Protects the filter: every row left must have the chosen value.',
        body: witnessed(rows, [`await ${code}.selectOption({ label: ${quote(option)} });`, ...filterAssertion(rows, option)]),
      },
    });
    break;
  }

  // Filter: a custom dropdown (ARIA combobox with options), as in MUI.
  if (!probes.some((probe) => probe.kind === 'filter')) {
    const filter = await comboboxFilter(page, rows);
    if (filter) probes.push(filter);
  }

  probes.push(...(await sortControlProbes(page, rows)));
  probes.push(...(await tableProbes(page, rows)));

  return probes;
}

/** Plain-JS body asserting every row has a cell equal to `option`. */
function filterAssertion(rows: string, option: string): string[] {
  return [
    `const rows = page.locator(${quote(rows)});`,
    'await expect(async () => {',
    '  const cells = await rows.evaluateAll((elements) =>',
    "    elements.map((row) => Array.from(row.querySelectorAll('td, [role=gridcell], [role=cell]')).map((cell) => cell.innerText.trim().toLowerCase()))",
    '  );',
    '  expect(cells.length, "rows left after filtering").toBeGreaterThan(0);',
    `  for (const row of cells) expect(row, "every row should show the chosen value").toContain(${quote(option.toLowerCase())});`,
    '}).toPass({ timeout: 10_000 });',
  ];
}

/** Lower-cased cell texts per visible row. */
async function rowCells(page: Page, rows: string): Promise<string[][]> {
  return page.locator(rows).evaluateAll((elements) =>
    elements.map((row) => Array.from(row.querySelectorAll('td, [role=gridcell], [role=cell]')).map((cell) => ((cell as HTMLElement).innerText || '').trim()))
  );
}

/** An option that some, but not all, rows show in a cell of their own. */
function splittingOption(options: string[], cells: string[][]): string | undefined {
  const lowered = cells.map((row) => row.map((cell) => cell.toLowerCase()));

  return options.find((candidate) => {
    const lower = candidate.toLowerCase();
    const matching = lowered.filter((row) => row.includes(lower)).length;
    return matching > 0 && matching < lowered.length;
  });
}

async function comboboxFilter(page: Page, rows: string): Promise<Probe | undefined> {
  const boxes = page.locator('[role=combobox]:visible');
  const count = Math.min(await boxes.count(), 10);

  for (let index = 0; index < count; index += 1) {
    const box = boxes.nth(index);

    const info = await box.evaluate((node) => {
      const element = node as HTMLElement;
      const labelledBy = element.getAttribute('aria-labelledby');
      const name = (
        element.getAttribute('aria-label') ||
        (labelledBy ? labelledBy.split(/\s+/).map((id) => document.getElementById(id)?.textContent ?? '').join(' ') : '') ||
        ''
      ).trim().replace(/\s+/g, ' ');

      return { name, chrome: !!element.closest('nav, header, [role=banner], [role=navigation], aside'), native: element.tagName === 'SELECT' };
    });

    if (!info.name || info.chrome || info.native || !FILTER_LABEL.test(info.name)) continue;
    if ((await page.getByRole('combobox', { name: info.name, exact: true }).count()) !== 1) continue;

    await box.click().catch(() => undefined);
    const options = (await page.getByRole('option').allInnerTexts().catch(() => [] as string[])).map((text) => text.trim()).filter(Boolean);
    await page.keyboard.press('Escape').catch(() => undefined);

    const option = splittingOption(options, await rowCells(page, rows));
    if (!option) continue;

    const code = `page.getByRole('combobox', { name: ${quote(info.name)}, exact: true })`;

    return {
      kind: 'filter',
      description: `Filtered by ${info.name} = "${option}": only rows showing "${option}" should remain`,
      setup: [],
      test: {
        title: `Filter "${option}" shows only "${option}" rows`,
        intent: 'Protects the filter: every row left must have the chosen value.',
        body: witnessed(rows, [
          `await ${code}.click();`,
          `await page.getByRole('option', { name: ${quote(option)}, exact: true }).click();`,
          ...filterAssertion(rows, option),
        ]),
      },
    };
  }

  return undefined;
}

