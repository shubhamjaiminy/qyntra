/**
 * Write AI-authored feature tests to disk and run them with Playwright.
 *
 * Each feature gets a self-contained suite:
 *
 *   features/<slug>/
 *     feature.config.cjs    Playwright config: session, browser profile
 *     qyntra-fixture.ts     opens the feature, waits for it, guards writes
 *     tests/NN-<title>.spec.ts
 *
 * The fixture embeds isWriteRequest's own source, so the tests enforce
 * the same read-only rule as exploration without importing Qyntra, and
 * keep working after Qyntra is uninstalled.
 */

import fs from 'fs';
import path from 'path';
import { spawnSync } from 'child_process';

import { readPageSnapshot } from './failure-evidence';
import { slug } from './feature-explorer';
import type { WrittenTest } from './feature-ai';
import { isWriteRequest } from './read-only-guard';

export interface SuiteOptions {
  dir: string;
  featureUrl: string;
  storageStatePath?: string;
  readOnly: boolean;
}

export interface TestRun {
  title: string;
  passed: boolean;
  error?: string;
  /** Aria snapshot of the page when the test failed, if Playwright saved one. */
  pageAtFailure?: string;
}

export function fixtureSource(options: SuiteOptions): string {
  return `// Generated by Qyntra. Opens the feature before each test${options.readOnly ? ' and blocks every write request' : ''}.
import { test as base, expect } from '@playwright/test';

export { expect };

const FEATURE_URL = ${JSON.stringify(options.featureUrl)};
const READ_ONLY = ${options.readOnly};

const isWriteRequest: (method: string, url: string, postData: string | null | undefined) => boolean = ${isWriteRequest.toString()};

/** Rendered, not merely loaded: no busy indicator, text stable. */
async function ready(page: any): Promise<void> {
  await page.waitForLoadState('networkidle', { timeout: 15_000 }).catch(() => undefined);
  let previous = '';
  for (let i = 0; i < 30; i += 1) {
    await page.waitForTimeout(1_000);
    const busy = await page.locator('[role=progressbar]:visible, [aria-busy=true]:visible').count().catch(() => 0);
    const text = await page.locator('body').innerText().catch(() => '');
    if (busy === 0 && text.length > 0 && text === previous) return;
    previous = text;
  }
}

export const test = base.extend<{ featurePage: void }>({
  featurePage: [
    async ({ page, context }, use) => {
      if (READ_ONLY) {
        await context.route('**/*', (route) => {
          const request = route.request();
          return isWriteRequest(request.method(), request.url(), request.postData())
            ? route.abort('blockedbyclient')
            : route.fallback();
        });
      }
      await page.goto(FEATURE_URL);
      await ready(page);
      await use();
    },
    { auto: true },
  ],
});
`;
}

export function configSource(options: SuiteOptions): string {
  return `// Generated by Qyntra. Run: npx playwright test -c ${path.basename(path.join(options.dir, 'feature.config.cjs'))}
const { devices } = require('@playwright/test');

module.exports = {
  testDir: './tests',
  timeout: 120000,
  expect: { timeout: 10000 },
  workers: 1,
  retries: 0,
  reporter: [['json', { outputFile: './results.json' }]],
  outputDir: './test-output',
  use: {
    ...devices['Desktop Chrome'],
    locale: 'en-US',
    viewport: { width: 1440, height: 900 },
    actionTimeout: 15000,
    screenshot: 'only-on-failure',
    ${options.storageStatePath ? `storageState: ${JSON.stringify(options.storageStatePath)},` : ''}
  },
};
`;
}

export function specSource(test: WrittenTest): string {
  const body = test.body
    .split('\n')
    .map((line) => `  ${line}`)
    .join('\n');

  return `// Generated by Qyntra. ${test.intent.replace(/\n/g, ' ')}
import { test, expect } from '../qyntra-fixture';

test(${JSON.stringify(test.title)}, async ({ page }) => {
${body}
});
`;
}

export function specFileName(index: number, test: WrittenTest): string {
  return `${String(index + 1).padStart(2, '0')}-${slug(test.title)}.spec.ts`;
}

export function prepareSuite(options: SuiteOptions): void {
  fs.rmSync(path.join(options.dir, 'tests'), { recursive: true, force: true });
  fs.mkdirSync(path.join(options.dir, 'tests'), { recursive: true });
  fs.writeFileSync(path.join(options.dir, 'qyntra-fixture.ts'), fixtureSource(options));
  fs.writeFileSync(path.join(options.dir, 'feature.config.cjs'), configSource(options));
}

export function writeSpec(dir: string, fileName: string, test: WrittenTest): string {
  const file = path.join(dir, 'tests', fileName);
  fs.writeFileSync(file, specSource(test));
  return file;
}

/** Strip ANSI colour codes from Playwright's error text. */
const plain = (text: string) => text.replace(/\u001b\[[0-9;]*m/g, '');

/**
 * Run the given spec files (all of tests/ when empty) and report each
 * test by title.
 */
export function runSpecs(dir: string, files: string[] = []): TestRun[] {
  const resultsFile = path.join(dir, 'results.json');
  fs.rmSync(resultsFile, { force: true });

  spawnSync(
    process.execPath,
    [require.resolve('@playwright/test/cli'), 'test', '-c', path.join(dir, 'feature.config.cjs'), ...files.map((file) => path.basename(file))],
    { cwd: dir, stdio: 'ignore', shell: false, env: process.env, timeout: 30 * 60_000 }
  );

  if (!fs.existsSync(resultsFile)) {
    return [];
  }

  const report = JSON.parse(fs.readFileSync(resultsFile, 'utf-8'));
  const runs: TestRun[] = [];

  const walk = (suite: any) => {
    for (const spec of suite.specs ?? []) {
      for (const entry of spec.tests ?? []) {
        const result = entry.results?.[entry.results.length - 1];
        const passed = result?.status === 'passed';
        const contextFile = result?.attachments?.find((attachment: any) => attachment.name === 'error-context')?.path;

        runs.push({
          title: spec.title,
          passed,
          ...(passed
            ? {}
            : {
                error: plain(String(result?.error?.message ?? result?.status ?? 'did not run')).slice(0, 3_000),
                pageAtFailure: contextFile ? readPageSnapshot(contextFile) : undefined,
              }),
        });
      }
    }

    for (const child of suite.suites ?? []) {
      walk(child);
    }
  };

  for (const suite of report.suites ?? []) {
    walk(suite);
  }

  // A compile error fails the whole file with no tests: surface it.
  for (const error of report.errors ?? []) {
    runs.push({ title: '(suite)', passed: false, error: plain(String(error?.message ?? error)).slice(0, 3_000) });
  }

  return runs;
}

/**
 * An assertion that saw a different value, as opposed to a test that
 * could not find its element. Only the former can be evidence that the
 * application is wrong.
 */
export function isValueMismatch(error: string): boolean {
  return /\bExpected\b/.test(error) && /\bReceived(?: string| value)?:\s*(?!<element)\S/.test(error);
}

/**
 * The test never got to run: DNS, connection, or the browser going
 * away. Re-run it as is; an AI "fix" for a network blip only damages a
 * test that was fine.
 */
export function isInfrastructureError(error: string): boolean {
  return /net::ERR_(NAME_NOT_RESOLVED|CONNECTION_(REFUSED|RESET|CLOSED|TIMED_OUT)|INTERNET_DISCONNECTED|NETWORK_CHANGED|TIMED_OUT)|Target page, context or browser has been closed|browserType\.launch/.test(
    error
  );
}

/**
 * Repair a strict-mode violation without a model. Playwright's error
 * lists every element the locator matched, each with a precise
 * alternative ("aka getByText('FILTERS', { exact: true })"). When
 * exactly one alternative names the same text the test asked for, that
 * is what the test meant.
 */
export function strictModeFix(body: string, error: string): string | undefined {
  const violation = /strict mode violation: (getBy\w+\((['"])((?:\\.|(?!\2).)*)\2(?:, \{[^}]*\})?\))/.exec(error);

  if (!violation) {
    return undefined;
  }

  const [, original, , text] = violation;

  const alternatives = [...error.matchAll(/aka (.+)$/gm)]
    .map((match) => match[1].trim())
    .filter((alternative) => !alternative.includes(').') && alternative.includes(`'${text}'`) && /exact: true/.test(alternative));

  if (alternatives.length !== 1 || !body.includes(original)) {
    return undefined;
  }

  return body.split(original).join(alternatives[0]);
}

/**
 * Split a test body into statements. Models put several on one line;
 * splitting before each `await` is enough for test bodies.
 */
export function statements(body: string): string[] {
  return body
    .split(/;\s*(?=(?:await|const|let)\s)|\n+/)
    .map((statement) => statement.trim().replace(/;$/, ''))
    .filter((statement) => statement !== '');
}

/**
 * The test with its actions removed: assertions only. If this still
 * passes, the actions never mattered and the test proves nothing about
 * the behaviour it names. Undefined when the test has no actions — a
 * pure presence check is honest about what it checks.
 */
export function assertionsOnly(body: string): string | undefined {
  const all = statements(body);
  const assertions = all.filter((statement) => /\bexpect\s*\(/.test(statement));

  if (assertions.length === all.length || assertions.length === 0) {
    return undefined;
  }

  return assertions.map((statement) => `${statement};`).join('\n');
}
